"""Downloaders for real public TCR-pMHC datasets, normalised to the canonical schema.

Each loader documents its **real public source URL** (see the module constants
:data:`VDJDB_URL`, :data:`MCPAS_URL`, :data:`IEDB_URL`, :data:`NETTCR_URL`),
downloads the raw table to a cache directory (default ``~/.cache/tcr_cliff`` or
``C:\\tcrtmp`` on Windows), parses it, and maps its columns onto the canonical
schema defined in :mod:`tcr_cliff.data.schema`.

This module **never fabricates rows**. If a download or parse fails for any reason
(network, format drift, licence wall) the loader raises :class:`RuntimeError`
pointing the user at ``DATASETS.md`` for manual-download instructions.

See ``DATASETS.md`` for the URL, licence, and citation of every source, and for an
explicit statement that the *bundled toy set is synthetic* (generated by
:mod:`tcr_cliff.data.toy._generate`) and must not be used for benchmark claims.
"""

from __future__ import annotations

import io
import os
import urllib.error
import urllib.request
import zipfile
from pathlib import Path

import pandas as pd

from tcr_cliff._logging import get_logger
from tcr_cliff.data.schema import ALL_COLUMNS, clean_sequence, validate_pairs

_log = get_logger("data.download")

# --------------------------------------------------------------------------- #
# Real public source URLs. These are the canonical, citeable download endpoints.
# They are NOT fetched during the build/test task; see DATASETS.md for details.
# --------------------------------------------------------------------------- #

#: VDJdb release pointer. ``latest-version.txt`` lists release ZIP URLs (newest
#: first); each ZIP contains ``vdjdb.slim.txt``. https://vdjdb.cdr3.net
VDJDB_URL = "https://raw.githubusercontent.com/antigenomics/vdjdb-db/master/latest-version.txt"

#: McPAS-TCR full database export (human + mouse). https://friedmanlab.weizmann.ac.il/McPAS-TCR/
#: The site migrated to an R/Shiny app; the old ``/Download/McPAS-TCR.csv`` path now
#: 404s, but the CSV is still served statically at the app root (this URL).
MCPAS_URL = "https://friedmanlab.weizmann.ac.il/McPAS-TCR/McPAS-TCR.csv"

#: IEDB receptor/TCR export portal. Programmatic CSV export from the T cell receptor table.
IEDB_URL = "https://www.iedb.org/downloader.php?file_name=doc/receptor_full_v3.zip"

#: NetTCR-2.0 / ImmRep training+test data (Montemurro et al. 2021).
NETTCR_URL = "https://raw.githubusercontent.com/mnielLab/NetTCR-2.0/main/data/train_beta_90.csv"

#: NetTCR-2.0 input column order (CDR3-beta + peptide + binder label).
NETTCR_COLUMNS: tuple[str, ...] = ("CDR3b", "peptide", "binder")

_DATASETS_HINT = (
    "See DATASETS.md for the source URL, licence, and manual-download "
    "instructions (place the file in the cache dir and re-run)."
)


# --------------------------------------------------------------------------- #
# Cache / download helpers
# --------------------------------------------------------------------------- #


def default_cache_dir() -> Path:
    """Return the default on-disk cache directory for downloaded datasets.

    Returns
    -------
    pathlib.Path
        ``~/.cache/tcr_cliff`` on POSIX, or ``C:\\tcrtmp`` on Windows. The
        directory is *not* created here; callers create it on demand.
    """
    if os.name == "nt":
        return Path(r"C:\tcrtmp")
    return Path.home() / ".cache" / "tcr_cliff"


def _resolve_cache_dir(cache_dir: str | Path | None) -> Path:
    """Resolve and create the cache directory for a download."""
    base = Path(cache_dir) if cache_dir is not None else default_cache_dir()
    base.mkdir(parents=True, exist_ok=True)
    return base


def _download(url: str, dest: Path, *, timeout: float = 60.0) -> Path:
    """Download ``url`` to ``dest`` (cached), returning the local path.

    Parameters
    ----------
    url:
        The remote source URL.
    dest:
        Local destination path. If it already exists it is returned unchanged
        (the cache hit), so repeated loads do not re-fetch.
    timeout:
        Socket timeout in seconds.

    Raises
    ------
    RuntimeError
        If the download fails for any reason. The message points at
        ``DATASETS.md`` so the user can fetch the file manually.
    """
    if dest.exists() and dest.stat().st_size > 0:
        _log.info("cache hit: %s", dest)
        return dest
    _log.info("downloading %s -> %s", url, dest)
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "tcr-cliff/0.1"})
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            data = resp.read()
        dest.write_bytes(data)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        raise RuntimeError(
            f"Failed to download {url!r} to {dest}: {exc}. {_DATASETS_HINT}"
        ) from exc
    if dest.stat().st_size == 0:
        raise RuntimeError(f"Downloaded empty file from {url!r}. {_DATASETS_HINT}")
    return dest


def _read_table(path: Path, *, sep: str = "\t") -> pd.DataFrame:
    """Read a cached delimited table (utf-8 then latin-1), raising a pointed error."""
    last: Exception | None = None
    # utf-8-sig strips a BOM (McPAS ships one); latin-1 is the last-resort fallback.
    for enc in ("utf-8-sig", "latin-1"):
        try:
            return pd.read_csv(path, sep=sep, low_memory=False, encoding=enc)
        except UnicodeDecodeError as exc:  # try the next encoding
            last = exc
            continue
        except Exception as exc:
            raise RuntimeError(f"Failed to parse {path}: {exc}. {_DATASETS_HINT}") from exc
    raise RuntimeError(f"Failed to parse {path}: {last}. {_DATASETS_HINT}")


def _flatten_iedb_header(top: object, sub: object) -> str:
    """Flatten an IEDB two-row header cell to ``"Group - Field"``.

    Keeping the group prefix is essential: the alpha (``Chain 1``) and beta
    (``Chain 2``) CDR3 columns share the field name ``CDR3 Curated`` and would
    otherwise collide into a single ambiguous column.
    """
    top, sub = str(top), str(sub)
    if "Unnamed" in sub:
        return top.strip()
    if "Unnamed" in top:
        return sub.strip()
    return f"{top} - {sub}".strip()


def _finalize(df: pd.DataFrame, source: str) -> pd.DataFrame:
    """Tag the source column and validate against the canonical schema.

    Parameters
    ----------
    df:
        A frame already carrying (at least) the required canonical columns.
    source:
        The source tag written into the ``source`` column.

    Raises
    ------
    RuntimeError
        If validation fails (e.g. no valid rows survived normalisation).
    """
    if df.empty:
        raise RuntimeError(f"{source} produced no rows after column mapping. {_DATASETS_HINT}")
    df = df.copy()
    df["source"] = source
    try:
        return validate_pairs(df)
    except Exception as exc:
        raise RuntimeError(
            f"{source} rows failed schema validation: {exc}. {_DATASETS_HINT}"
        ) from exc


def _first_present(df: pd.DataFrame, candidates: tuple[str, ...]) -> str | None:
    """Return the first column name in ``candidates`` that exists in ``df``."""
    lower = {c.lower(): c for c in df.columns}
    for cand in candidates:
        if cand in df.columns:
            return cand
        if cand.lower() in lower:
            return lower[cand.lower()]
    return None


