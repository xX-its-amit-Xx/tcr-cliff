def load_vdjdb(cache_dir: str | Path | None = None) -> pd.DataFrame:
    """Download and load VDJdb, mapped to the canonical schema.

    Source
    ------
    VDJdb full export (``latest-version.txt``), a tab-separated table of curated
    TCR-epitope specificity records: :data:`VDJDB_URL`.

    Parameters
    ----------
    cache_dir:
        Directory to cache the raw download. Defaults to
        :func:`default_cache_dir`.

    Returns
    -------
    pandas.DataFrame
        Canonical-schema pairs frame (binder defaults to 1: VDJdb lists positive
        specificities only).

    Raises
    ------
    RuntimeError
        On any download/parse/mapping failure; the message points at
        ``DATASETS.md``.
    """
    cache = _resolve_cache_dir(cache_dir)
    # 'latest-version.txt' lists release ZIP URLs (newest first); follow the first.
    ver_path = _download(VDJDB_URL, cache / "vdjdb_latest.txt")
    urls = [ln.strip() for ln in ver_path.read_text().splitlines() if ln.strip().startswith("http")]
    if not urls:
        raise RuntimeError(f"VDJdb latest-version.txt had no release URL. {_DATASETS_HINT}")
    zip_path = _download(urls[0], cache / Path(urls[0]).name)
    try:
        with zipfile.ZipFile(zip_path) as zf:
            members = [n for n in zf.namelist() if n.endswith("vdjdb.slim.txt")] or [
                n for n in zf.namelist() if n.endswith("vdjdb.txt")
            ]
            if not members:
                raise RuntimeError(f"No vdjdb table inside {zip_path}. {_DATASETS_HINT}")
            with zf.open(members[0]) as fh:
                raw = pd.read_csv(fh, sep="\t", low_memory=False)
    except zipfile.BadZipFile as exc:
        raise RuntimeError(f"VDJdb release not a valid ZIP: {exc}. {_DATASETS_HINT}") from exc

    cdr3 = _first_present(raw, ("cdr3", "CDR3", "cdr3b", "CDR3.beta"))
    pep = _first_present(raw, ("antigen.epitope", "Epitope", "antigen", "peptide"))
    gene = _first_present(raw, ("gene", "Gene"))
    if cdr3 is None or pep is None:
        raise RuntimeError(
            f"VDJdb columns not recognised (have {list(raw.columns)[:12]}...). " f"{_DATASETS_HINT}"
        )

    # VDJdb mixes TRA/TRB; keep beta chains when a gene column is present.
    if gene is not None:
        raw = raw.loc[raw[gene].astype(str).str.upper().str.contains("TRB", na=False)]

    mhc = _first_present(raw, ("mhc.a", "MHC A", "mhc_a"))
    vg = _first_present(raw, ("v.segm", "V", "v_gene"))
    jg = _first_present(raw, ("j.segm", "J", "j_gene"))

    out = pd.DataFrame(
        {
            "cdr3b": raw[cdr3].map(clean_sequence),
            "peptide": raw[pep].map(clean_sequence),
            "binder": 1,
        }
    )
    out["mhc"] = raw[mhc].astype(str).values if mhc else ""
    out["v_gene"] = raw[vg].astype(str).values if vg else ""
    out["j_gene"] = raw[jg].astype(str).values if jg else ""
    out["pair_id"] = [f"vdjdb{i:06d}" for i in range(len(out))]
    return _finalize(out, "vdjdb")


def load_mcpas(cache_dir: str | Path | None = None) -> pd.DataFrame:
    """Download and load McPAS-TCR, mapped to the canonical schema.

    Source
    ------
    McPAS-TCR full database CSV (Tickotsky et al. 2017): :data:`MCPAS_URL`.

    Parameters
    ----------
    cache_dir:
        Directory to cache the raw download. Defaults to
        :func:`default_cache_dir`.

    Returns
    -------
    pandas.DataFrame
        Canonical-schema pairs frame (binder=1; McPAS lists associations only).

    Raises
    ------
    RuntimeError
        On any download/parse/mapping failure; the message points at
        ``DATASETS.md``.
    """
    cache = _resolve_cache_dir(cache_dir)
    dest = cache / "McPAS-TCR.csv"
    if not (dest.exists() and dest.stat().st_size > 0):
        _download(MCPAS_URL, dest)
    # Defensive: if the app moves again and the URL 404s to an HTML page, detect that
    # and point the user at the manual-download fallback rather than parsing HTML.
    if dest.read_bytes()[:64].lstrip()[:1] == b"<":
        dest.unlink(missing_ok=True)
        raise RuntimeError(
            "McPAS-TCR returned HTML, not CSV (the app URL may have moved again). "
            "Download 'McPAS-TCR.csv' manually from "
            f"https://friedmanlab.weizmann.ac.il/McPAS-TCR/ and place it at {dest}, then "
            f"re-run. {_DATASETS_HINT}"
        )
    raw = _read_table(dest, sep=",")

    cdr3 = _first_present(raw, ("CDR3.beta.aa", "CDR3b", "CDR3.beta", "cdr3b"))
    pep = _first_present(raw, ("Epitope.peptide", "Epitope", "peptide"))
    if cdr3 is None or pep is None:
        raise RuntimeError(
            f"McPAS columns not recognised (have {list(raw.columns)[:12]}...). " f"{_DATASETS_HINT}"
        )

    mhc = _first_present(raw, ("MHC", "HLA"))
    vg = _first_present(raw, ("TRBV", "V"))
    jg = _first_present(raw, ("TRBJ", "J"))

    out = pd.DataFrame(
        {
            "cdr3b": raw[cdr3].map(clean_sequence),
            "peptide": raw[pep].map(clean_sequence),
            "binder": 1,
        }
    )
    out["mhc"] = raw[mhc].astype(str).values if mhc else ""
    out["v_gene"] = raw[vg].astype(str).values if vg else ""
    out["j_gene"] = raw[jg].astype(str).values if jg else ""
    out["pair_id"] = [f"mcpas{i:06d}" for i in range(len(out))]
    return _finalize(out, "mcpas")


def load_iedb(cache_dir: str | Path | None = None) -> pd.DataFrame:
    """Download and load the IEDB TCR receptor export, mapped to the schema.

    Source
    ------
    IEDB receptor (TCR) full export: :data:`IEDB_URL`. IEDB serves a ZIP; the
    CSV inside it is parsed.

    Parameters
    ----------
    cache_dir:
        Directory to cache the raw download. Defaults to
        :func:`default_cache_dir`.

    Returns
    -------
    pandas.DataFrame
        Canonical-schema pairs frame.

    Raises
    ------
    RuntimeError
        On any download/parse/mapping failure; the message points at
        ``DATASETS.md``.
    """
    cache = _resolve_cache_dir(cache_dir)
    path = _download(IEDB_URL, cache / "iedb_receptor_full_v3.zip")
    try:
        with zipfile.ZipFile(path) as zf:
            members = [n for n in zf.namelist() if n.lower().endswith(".csv")]
            if not members:
                raise RuntimeError(f"No CSV inside IEDB archive {path}. {_DATASETS_HINT}")
            with zf.open(members[0]) as fh:
                raw = pd.read_csv(io.BytesIO(fh.read()), low_memory=False, header=[0, 1])
        # IEDB uses a two-row (group, field) header; keep the group to disambiguate the
        # alpha (Chain 1) and beta (Chain 2) CDR3 columns.
        raw.columns = [_flatten_iedb_header(a, b) for a, b in raw.columns]
    except RuntimeError:
        raise
    except Exception as exc:
        raise RuntimeError(f"Failed to read IEDB archive {path}: {exc}. {_DATASETS_HINT}") from exc

    # The TCR beta chain is "Chain 2"; the epitope sequence lives in "Epitope - Name".
    cdr3 = _first_present(
        raw, ("Chain 2 - CDR3 Curated", "Chain 2 - CDR3 Calculated", "Chain 2 CDR3 Curated")
    )
    pep = _first_present(raw, ("Epitope - Name", "Epitope - Description", "Description", "Epitope"))
    if cdr3 is None or pep is None:
        raise RuntimeError(
            f"IEDB columns not recognised (have {list(raw.columns)[:12]}...). " f"{_DATASETS_HINT}"
        )
    mhc = _first_present(raw, ("Assay - MHC Allele Names", "MHC Allele Names", "MHC", "HLA"))

    out = pd.DataFrame(
        {
            "cdr3b": raw[cdr3].map(clean_sequence),
            "peptide": raw[pep].map(clean_sequence),
            "binder": 1,
        }
    )
    out["mhc"] = raw[mhc].astype(str).values if mhc else ""
    out["pair_id"] = [f"iedb{i:06d}" for i in range(len(out))]
    return _finalize(out, "iedb")


def load_nettcr(cache_dir: str | Path | None = None) -> pd.DataFrame:
    """Download and load the NetTCR-2.0 / ImmRep dataset, mapped to the schema.

    Source
    ------
    NetTCR-2.0 training data (Montemurro et al. 2021): :data:`NETTCR_URL`. This
    is the dataset whose ``CDR3b, peptide, binder`` layout :func:`to_nettcr_format`
    targets. Unlike VDJdb/McPAS/IEDB it carries explicit negative (binder=0) rows.

    Parameters
    ----------
    cache_dir:
        Directory to cache the raw download. Defaults to
        :func:`default_cache_dir`.

    Returns
    -------
    pandas.DataFrame
        Canonical-schema pairs frame with real 0/1 binder labels.

    Raises
    ------
    RuntimeError
        On any download/parse/mapping failure; the message points at
        ``DATASETS.md``.
    """
    cache = _resolve_cache_dir(cache_dir)
    path = _download(NETTCR_URL, cache / "nettcr_train_beta.csv")
    raw = _read_table(path, sep=",")

    cdr3 = _first_present(raw, ("CDR3b", "cdr3b", "CDR3", "cdr3"))
    pep = _first_present(raw, ("peptide", "Peptide", "epitope"))
    label = _first_present(raw, ("binder", "label", "y"))
    if cdr3 is None or pep is None:
        raise RuntimeError(
            f"NetTCR columns not recognised (have {list(raw.columns)[:12]}...). "
            f"{_DATASETS_HINT}"
        )

    out = pd.DataFrame(
        {
            "cdr3b": raw[cdr3].map(clean_sequence),
            "peptide": raw[pep].map(clean_sequence),
        }
    )
    out["binder"] = raw[label].astype("float").round().astype("int") if label else 1
    out["pair_id"] = [f"nettcr{i:06d}" for i in range(len(out))]
    return _finalize(out, "nettcr")


