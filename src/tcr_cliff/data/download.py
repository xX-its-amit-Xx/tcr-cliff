def to_nettcr_format(df: pd.DataFrame) -> pd.DataFrame:
    """Convert a canonical-schema frame into NetTCR-2.0 input columns.

    NetTCR-2.0 consumes a CSV with at least ``CDR3b``, ``peptide`` and a
    ``binder`` label column (see :data:`NETTCR_COLUMNS`).

    Parameters
    ----------
    df:
        Any canonical-schema pairs frame (e.g. ``load_toy()``). It is validated
        first so callers cannot accidentally pass a malformed table.

    Returns
    -------
    pandas.DataFrame
        Columns ``CDR3b, peptide, binder`` (plus ``MHC`` when ``mhc`` is present
        and non-empty).
    """
    norm = validate_pairs(df)
    out = pd.DataFrame(
        {
            "CDR3b": norm["cdr3b"].astype(str),
            "peptide": norm["peptide"].astype(str),
            "binder": norm["binder"].astype(int),
        }
    )
    if "mhc" in norm.columns and norm["mhc"].astype(str).str.len().gt(0).any():
        out["MHC"] = norm["mhc"].astype(str)
    return out


def write_nettcr_csv(df: pd.DataFrame, path: str | Path) -> Path:
    """Write a canonical frame to a NetTCR-2.0 input CSV.

    Parameters
    ----------
    df:
        Canonical-schema pairs frame.
    path:
        Destination CSV path; parent directories are created as needed.

    Returns
    -------
    pathlib.Path
        The path written.
    """
    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    to_nettcr_format(df).to_csv(dest, index=False)
    _log.info("wrote NetTCR-format CSV: %s", dest)
    return dest


def cdr3_from_anarci(sequence: str, scheme: str = "imgt") -> str | None:
    """Extract the CDR3 loop from a full TCR-beta variable sequence via ANARCI.

    Parameters
    ----------
    sequence:
        A full TCR variable-domain amino-acid sequence.
    scheme:
        Numbering scheme passed to ANARCI (default ``"imgt"``). Under IMGT the
        CDR3 spans positions 105-117 inclusive.

    Returns
    -------
    str or None
        The CDR3 substring, or ``None`` if ANARCI cannot number the sequence.

    Raises
    ------
    ImportError
        If ``anarci`` is not installed. Install it with
        ``pip install 'tcr-cliff[full]'`` (ANARCI is distributed via Bioconda).
    """
    try:
        from anarci import anarci as _anarci  # type: ignore[import-not-found]
    except ImportError as exc:  # pragma: no cover - exercised only without anarci
        raise ImportError(
            "cdr3_from_anarci requires the 'anarci' package, which is not "
            "installed. Install it via Bioconda (conda install -c bioconda anarci) "
            "or 'pip install ANARCI'."
        ) from exc

    seq = clean_sequence(sequence)
    if not seq:
        return None
    numbering, _details, _hits = _anarci([("query", seq)], scheme=scheme, output=False)
    if not numbering or numbering[0] is None:
        return None
    # numbering[0] is a list of domains; take the first domain's numbered list.
    domain = numbering[0][0][0]
    cdr3 = [aa for (pos, _ins), aa in domain if 105 <= pos <= 117 and aa != "-"]
    seq_out = "".join(cdr3)
    return seq_out or None


